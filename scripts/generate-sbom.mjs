import { execFileSync } from "node:child_process";
import { readFile, rename, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";

const repository = basename(process.cwd());
const configPath = resolve("sbom.config.json");
const jsonOutputPath = resolve("SBOM.cdx.json");
const csvOutputPath = resolve("SBOM.csv");
const jsonTemporaryPath = `${jsonOutputPath}.tmp`;
const csvTemporaryPath = `${csvOutputPath}.tmp`;

function run(command, args) {
  return execFileSync(command, args, {
    cwd: process.cwd(),
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  });
}

function generateDependencyBom() {
  const args = [
    "sbom",
    "--sbom-format",
    "cyclonedx",
    "--sbom-spec-version",
    "1.6",
    "--sbom-type",
    "application",
  ];
  const pnpmCli = process.env.npm_execpath;

  return pnpmCli
    ? run(process.execPath, [pnpmCli, ...args])
    : run("pnpm", args);
}

function getProperty(component, name) {
  return component.properties?.find((entry) => entry.name === name)?.value;
}

function setProperty(component, name, value) {
  const properties = component.properties ?? [];
  const existing = properties.find((entry) => entry.name === name);
  if (existing) existing.value = value;
  else properties.push({ name, value });
  component.properties = properties;
}

function npmName(component) {
  return component.group ? `${component.group}/${component.name}` : component.name;
}

function dependencyClosure(startRefs, dependencyMap) {
  const visited = new Set();
  const pending = [...startRefs];

  while (pending.length > 0) {
    const current = pending.pop();
    if (current == null || visited.has(current)) continue;
    visited.add(current);
    pending.push(...(dependencyMap.get(current) ?? []));
  }

  return visited;
}

function addRepositoryMetadata(bom, packageJson) {
  const root = bom.metadata.component;
  const dependencyMap = new Map(
    bom.dependencies.map((entry) => [entry.ref, entry.dependsOn ?? []]),
  );
  const componentsByName = new Map(
    bom.components.map((component) => [npmName(component), component]),
  );
  const runtimeDirectNames = new Set(Object.keys(packageJson.dependencies ?? {}));
  const developmentDirectNames = new Set(Object.keys(packageJson.devDependencies ?? {}));
  const runtimeDirectRefs = [...runtimeDirectNames]
    .map((name) => componentsByName.get(name)?.["bom-ref"])
    .filter(Boolean);
  const developmentDirectRefs = [...developmentDirectNames]
    .map((name) => componentsByName.get(name)?.["bom-ref"])
    .filter(Boolean);
  const runtimeRefs = dependencyClosure(runtimeDirectRefs, dependencyMap);
  const developmentRefs = dependencyClosure(developmentDirectRefs, dependencyMap);

  setProperty(root, "sbom:repository", repository);
  setProperty(root, "sbom:ecosystem", "first-party");
  setProperty(root, "sbom:relationship", "root component");
  setProperty(root, "sbom:metadata-source", `${repository}/package.json`);
  setProperty(root, "sbom:notes", "First-party repository component.");

  try {
    setProperty(root, "vcs:commit", run("git", ["rev-parse", "HEAD"]).trim());
    const status = run("git", ["status", "--porcelain"]).trim();
    setProperty(root, "sbom:source-state", status === "" ? "clean" : "modified working tree");
  } catch {
    setProperty(root, "sbom:source-state", "Git state unavailable");
  }

  for (const component of bom.components) {
    const name = npmName(component);
    const ref = component["bom-ref"];
    let relationship;

    if (runtimeDirectNames.has(name)) relationship = "direct runtime dependency";
    else if (developmentDirectNames.has(name)) relationship = "direct development dependency";
    else if (runtimeRefs.has(ref)) relationship = "transitive runtime dependency";
    else if (developmentRefs.has(ref)) relationship = "transitive development dependency";
    else relationship = "installed transitive dependency (reachability unresolved)";

    setProperty(component, "sbom:repository", repository);
    setProperty(component, "sbom:ecosystem", "npm");
    setProperty(component, "sbom:relationship", relationship);
    setProperty(
      component,
      "sbom:metadata-source",
      `${repository}/pnpm-lock.yaml and installed package metadata`,
    );
    setProperty(
      component,
      "sbom:notes",
      "Generated by pnpm's native CycloneDX SBOM command.",
    );
  }
}

function requiredConfigString(value, location) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${location} must be a non-empty string`);
  }
  return value;
}

function addConfiguredComponents(bom, config) {
  if (!Array.isArray(config.additionalComponents)) {
    throw new Error("sbom.config.json must contain an additionalComponents array");
  }

  const components = config.additionalComponents.map((configured, index) => {
    const location = `sbom.config.json additionalComponents[${index}]`;
    if (configured == null || typeof configured !== "object" || Array.isArray(configured)) {
      throw new Error(`${location} must be an object`);
    }

    const {
      ecosystem,
      relationship,
      metadataSource,
      notes,
      ...component
    } = configured;
    requiredConfigString(component.type, `${location}.type`);
    requiredConfigString(component["bom-ref"], `${location}.bom-ref`);
    requiredConfigString(component.name, `${location}.name`);
    requiredConfigString(component.version, `${location}.version`);
    requiredConfigString(ecosystem, `${location}.ecosystem`);
    requiredConfigString(relationship, `${location}.relationship`);
    requiredConfigString(metadataSource, `${location}.metadataSource`);
    requiredConfigString(notes, `${location}.notes`);
    if (component.properties != null && !Array.isArray(component.properties)) {
      throw new Error(`${location}.properties must be an array when provided`);
    }

    setProperty(component, "sbom:repository", repository);
    setProperty(component, "sbom:ecosystem", ecosystem);
    setProperty(component, "sbom:relationship", relationship);
    setProperty(
      component,
      "sbom:metadata-source",
      `${repository}/${metadataSource}`,
    );
    setProperty(component, "sbom:notes", notes);
    return component;
  });

  bom.components.push(...components);

  const rootRef = bom.metadata.component["bom-ref"];
  let rootDependencies = bom.dependencies.find((entry) => entry.ref === rootRef);
  if (!rootDependencies) {
    rootDependencies = { ref: rootRef, dependsOn: [] };
    bom.dependencies.unshift(rootDependencies);
  }
  rootDependencies.dependsOn ??= [];
  rootDependencies.dependsOn.push(
    ...components.map((component) => component["bom-ref"]),
  );
  rootDependencies.dependsOn = [...new Set(rootDependencies.dependsOn)].sort();
}

function addGenerationMetadata(bom) {
  bom.metadata.tools ??= { components: [] };
  bom.metadata.tools.components ??= [];
  bom.metadata.tools.components.push({
    type: "application",
    name: "repository SBOM enrichment script",
    version: "1",
  });
  bom.metadata.properties = [
    {
      name: "sbom:scope",
      value:
        "This repository's first-party package, installed pnpm dependency inventory, and additional container/system software declared in sbom.config.json",
    },
    {
      name: "sbom:container-detail",
      value:
        "Configured base image components are inventory references; their packages are not expanded. Explicitly installed system software is listed through sbom.config.json",
    },
    {
      name: "sbom:license-method",
      value:
        "pnpm native package metadata plus repository declarations for first-party and referenced software",
    },
    {
      name: "sbom:unresolved-policy",
      value:
        "Missing licenses, NOASSERTION, and not-pinned markers are retained for manual review; no license is guessed",
    },
  ];
}

function validateBom(bom, packageJson) {
  if (bom.bomFormat !== "CycloneDX" || bom.specVersion !== "1.6") {
    throw new Error("pnpm did not generate the requested CycloneDX 1.6 document");
  }

  const allComponents = [bom.metadata.component, ...bom.components];
  const refs = allComponents.map((component) => component["bom-ref"]);
  const uniqueRefs = new Set(refs);
  if (refs.some((ref) => typeof ref !== "string" || ref === "")) {
    throw new Error("SBOM contains a component without a bom-ref");
  }
  if (uniqueRefs.size !== refs.length) {
    throw new Error("SBOM contains duplicate component bom-ref values");
  }

  const dependencyRefs = bom.dependencies.flatMap((entry) => [
    entry.ref,
    ...(entry.dependsOn ?? []),
  ]);
  const danglingRefs = [...new Set(dependencyRefs.filter((ref) => !uniqueRefs.has(ref)))];
  if (danglingRefs.length > 0) {
    throw new Error(`SBOM contains dangling dependency references: ${danglingRefs.join(", ")}`);
  }

  const directNames = new Set([
    ...Object.keys(packageJson.dependencies ?? {}),
    ...Object.keys(packageJson.devDependencies ?? {}),
  ]);
  const componentNames = new Set(bom.components.map(npmName));
  const missingDirectDependencies = [...directNames].filter(
    (name) => !componentNames.has(name),
  );
  if (missingDirectDependencies.length > 0) {
    throw new Error(
      `SBOM omits direct dependencies: ${missingDirectDependencies.join(", ")}`,
    );
  }
}

function csvValue(value) {
  const text = String(value ?? "");
  return /[",\r\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

function licenseValue(component) {
  const licenses = (component.licenses ?? []).map(
    ({ license, expression }) =>
      expression ?? license?.id ?? license?.name ?? "NOASSERTION",
  );
  return licenses.length > 0 ? licenses.join(" AND ") : "NOASSERTION";
}

function csvRow(component) {
  const relationship = getProperty(component, "sbom:relationship") ?? "";
  const dependencyScope = relationship.includes("development")
    ? "development"
    : "runtime/build";

  return [
    repository,
    component.type,
    getProperty(component, "sbom:ecosystem") ?? "",
    component.type === "library" && component.group
      ? npmName(component)
      : component.name,
    component.version,
    dependencyScope,
    relationship,
    licenseValue(component),
    component.purl ?? component["bom-ref"],
    getProperty(component, "sbom:metadata-source") ?? "",
    getProperty(component, "sbom:notes") ?? "",
  ]
    .map(csvValue)
    .join(",");
}

function createCsv(bom) {
  const header = [
    "Repository",
    "Component Type",
    "Ecosystem",
    "Name",
    "Version",
    "Dependency Scope",
    "Relationship",
    "License",
    "PURL or Reference",
    "Metadata Source",
    "Notes",
  ].join(",");
  const components = [bom.metadata.component, ...bom.components].sort((left, right) => {
    const rank = (component) => {
      if (component === bom.metadata.component) return 0;
      if (component.type === "container") return 1;
      if (getProperty(component, "sbom:ecosystem") === "Alpine package") return 2;
      return 3;
    };
    return rank(left) - rank(right) || npmName(left).localeCompare(npmName(right));
  });

  return `${[header, ...components.map(csvRow)].join("\r\n")}\r\n`;
}

const packageJson = JSON.parse(await readFile("package.json", "utf8"));
const sbomConfig = JSON.parse(await readFile(configPath, "utf8"));
const bom = JSON.parse(generateDependencyBom());
addRepositoryMetadata(bom, packageJson);
addConfiguredComponents(bom, sbomConfig);
addGenerationMetadata(bom);
validateBom(bom, packageJson);

await writeFile(jsonTemporaryPath, `${JSON.stringify(bom, null, 2)}\n`);
await writeFile(csvTemporaryPath, createCsv(bom));
await rename(jsonTemporaryPath, jsonOutputPath);
await rename(csvTemporaryPath, csvOutputPath);

console.log(
  `Generated ${basename(jsonOutputPath)} and ${basename(csvOutputPath)} with ${bom.components.length} components.`,
);
